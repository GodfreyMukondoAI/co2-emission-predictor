import {
  AlertCircle,
  CheckCircle2,
  Leaf,
  Gauge,
  Fuel,
} from "lucide-react";

import type { PredictionResponse } from "../../types/prediction";

interface PredictionResultProps {
  prediction: PredictionResponse | null;
  error: string | null;
}

function PredictionResult({
  prediction,
  error,
}: PredictionResultProps) {
  if (error) {
    return (
      <div className="flex min-h-[420px] items-center justify-center rounded-2xl border border-red-200 bg-red-50 p-8">
        <div className="max-w-md text-center">
          <div className="mx-auto flex h-14 w-14 items-center justify-center rounded-full bg-red-100 text-red-600">
            <AlertCircle size={28} />
          </div>

          <h3 className="mt-5 text-lg font-bold text-red-900">
            Prediction failed
          </h3>

          <p className="mt-2 text-sm leading-6 text-red-700">
            {error}
          </p>
        </div>
      </div>
    );
  }

  if (!prediction) {
    return (
      <div className="flex min-h-[420px] items-center justify-center rounded-2xl border border-dashed border-slate-300 bg-slate-50 p-8">
        <div className="max-w-md text-center">
          <div className="mx-auto flex h-16 w-16 items-center justify-center rounded-2xl bg-white text-emerald-600 shadow-sm">
            <Leaf size={30} />
          </div>

          <h3 className="mt-5 text-lg font-bold text-slate-950">
            Your prediction will appear here
          </h3>

          <p className="mt-2 text-sm leading-6 text-slate-500">
            Enter your vehicle details and run the
            prediction model to receive an estimated
            CO₂ emission value.
          </p>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-[420px] rounded-2xl border border-emerald-200 bg-gradient-to-br from-emerald-50 via-white to-white p-8">
      <div className="flex items-center gap-2 text-sm font-semibold text-emerald-700">
        <CheckCircle2 size={19} />

        <span>Prediction complete</span>
      </div>

      <div className="mt-10">
        <p className="text-sm font-medium text-slate-500">
          Estimated CO₂ emissions
        </p>

        <div className="mt-2 flex items-end gap-3">
          <span className="text-5xl font-bold tracking-tight text-slate-950">
            {prediction.predicted_co2.toFixed(2)}
          </span>

          <span className="pb-1 text-lg font-medium text-slate-500">
            {prediction.unit || "g/km"}
          </span>
        </div>
      </div>

      <div className="mt-10 grid gap-4 sm:grid-cols-2">
        <div className="rounded-xl border border-slate-200 bg-white p-4">
          <div className="flex items-center gap-2 text-slate-400">
            <Gauge size={17} />

            <p className="text-xs font-medium">
              Engine Size
            </p>
          </div>

          <p className="mt-2 text-lg font-bold text-slate-950">
            {prediction.engine_size.toFixed(1)} L
          </p>
        </div>

        <div className="rounded-xl border border-slate-200 bg-white p-4">
          <div className="flex items-center gap-2 text-slate-400">
            <Fuel size={17} />

            <p className="text-xs font-medium">
              Fuel Consumption
            </p>
          </div>

          <p className="mt-2 text-lg font-bold text-slate-950">
            {prediction.fuel_consumption_mpg.toFixed(1)} MPG
          </p>
        </div>
      </div>

      <div className="mt-8 rounded-xl border border-emerald-100 bg-white/70 p-4">
        <div className="flex gap-3">
          <Leaf
            size={18}
            className="mt-0.5 shrink-0 text-emerald-600"
          />

          <p className="text-xs leading-5 text-slate-500">
            This value is an estimate generated by the
            trained Multiple Linear Regression model.
            It is not an official vehicle emissions
            certification.
          </p>
        </div>
      </div>
    </div>
  );
}

export default PredictionResult;